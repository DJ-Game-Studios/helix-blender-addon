#!/usr/bin/env python3
"""Generate helix_blender_tools/_vocab.py from the helix-core animation vocabulary.

The addon runs standalone inside Blender, so it cannot import helix-core at
runtime. This writes a self-contained copy of the character names it needs,
stamped with the vocabulary version and digest. tests/test_vocab.py fails when
the copy drifts from the crate. Run after a vocabulary change:

    python3 scripts/gen_vocab.py            # finds ../helix-core (or HELIX_CORE_ROOT)
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "helix_blender_tools" / "_vocab.py"
JSON_REL = Path("crates/helix-anim-vocab/docs/engine_animations.json")


def locate() -> Path:
    root = os.environ.get("HELIX_CORE_ROOT", "").strip()
    candidates = [Path(root)] if root else [REPO.parent / "helix-core"]
    for c in candidates:
        if (c / JSON_REL).is_file():
            return c / JSON_REL
    raise SystemExit("helix-core not found: set HELIX_CORE_ROOT")


def render(data: dict) -> str:
    chars = [n for n in data["names"] if n["domain"] == "character"]
    # Templates: the v2 set, renamed to v3 (names from v1/v2 plus the targets
    # of the space-separated v2 spellings).
    renamed = {a["to"] for a in data["aliases"] if " " in a["from"]}
    templates = [n["name"] for n in chars if n["since"] <= 2 or n["name"] in renamed]
    names = {
        n["name"]: {
            "type": "loop" if n["loop_type"] in ("loop", "ping_pong") else "oneshot",
            "category": n["category"],
        }
        for n in chars
    }
    aliases = {a["from"]: a["to"] for a in data["aliases"]}
    lines = [
        "# GENERATED by scripts/gen_vocab.py from helix-core helix-anim-vocab — do not edit.",
        f"# Vocabulary v{data['vocab_version']}, {data['digest']}.",
        '"""Helix animation vocabulary (character names) for the standalone addon."""',
        "",
        f"VOCAB_VERSION = {data['vocab_version']}",
        f"VOCAB_DIGEST = {data['digest']!r}",
        "",
        "# name -> {type (manifest loop spelling), category}",
        "KNOWN_ANIMATIONS = " + json.dumps(names, indent=4, sort_keys=False),
        "",
        "# Names the 'Generate Animation Template' button creates.",
        "TEMPLATE_NAMES = " + json.dumps(templates, indent=4),
        "",
        "# Old spellings (including the v1 'Jump Start' style) -> current name.",
        "ALIASES = " + json.dumps(aliases, indent=4, sort_keys=True),
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render(json.loads(locate().read_text()))
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print("_vocab.py is stale: run scripts/gen_vocab.py", file=sys.stderr)
            return 1
        print("_vocab.py is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
